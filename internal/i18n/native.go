func init() {
	for key, text := range nativeMessages {
		if _, dup := messages[key]; dup {
			panic("duplicate i18n key: " + key)
		}
		messages[key] = text
	}
}

// Matches 判断 text 是否为 key 在任一语言下的文案。用于把切换语言前保存的显示文案映射回原选项。
func Matches(key, text string) bool {
	mu.RLock()
	defer mu.RUnlock()
	for _, candidate := range messages[key] {
		if candidate == text {
			return true
		}
	}
	return false
}
